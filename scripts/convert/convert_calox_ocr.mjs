function processOCR() {
  const lines = ocrText.trim().split('\n');
  const products = [];

  for (const line of lines) {
    if (line.includes('Codigo') || line.includes('LISTA DE PRECIO')) continue;

    const parts = line.split(' ');
    
    // Last part is Bonificacion (e.g. 50%)
    let bonificacionRaw = parts.pop();
    let descuento_porcentaje = parseFloat(bonificacionRaw.replace('%', ''));

    // Second to last is Precio Publico
    let precioPublico = parts.pop();
    
    // Third to last is Precio Farmacia
    let precioFarmaciaRaw = parts.pop();
    let precio_base = parseFloat(precioFarmaciaRaw.replace(/,/g, ''));
    
    if (isNaN(precio_base)) continue;

    const codigo = parts[0];
    parts.shift();
    const nombre = parts.join(' ').trim();

    products.push({
      codigo_proveedor: codigo,
      nombre_producto: nombre,
      proveedor: 'CALOX',
      precio_base: precio_base,
      descuento_porcentaje: isNaN(descuento_porcentaje) ? 0 : descuento_porcentaje
    });
  }

  const csv = stringify(products, { header: true });
  fs.writeFileSync('C:/Users/F Conrado/.gemini/antigravity-ide/brain/a75abecc-2c40-44df-92eb-3eac18935bd1/scratch/catalogo_calox.csv', csv);
  console.log(`Converted ${products.length} products to catalogo_calox.csv`);
}

